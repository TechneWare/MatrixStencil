    public static IEnumerable<char> SupportedCharacters => Glyphs.Keys;

    public static bool IsSupported(char character)
    {
        return Glyphs.ContainsKey(character);
    }

    public static bool TryGet(char character, out BitmapGlyph glyph)
    {
        return Glyphs.TryGetValue(character, out glyph!);
    }

    public static BitmapGlyph Get(char character)
    {
        if (TryGet(character, out var glyph))
        {
            return glyph;
        }

        throw new ArgumentException(
            $"Character U+{(int)character:X4} is not a printable ASCII glyph.",
            nameof(character));
    }
